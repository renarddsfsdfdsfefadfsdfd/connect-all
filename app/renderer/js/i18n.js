window.T = function T(key, vars) {
  const lang = window.CA_LANG || 'zh';
  const table = window.CA_I18N[lang] || window.CA_I18N.zh;
  let text = table[key];
  if (text == null) text = (window.CA_I18N.zh && window.CA_I18N.zh[key]) || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(new RegExp('\\{' + k + '\\}', 'g'), String(v));
    }
  }
  return text;
};
